const dictionaries: Record<"en" | "ro", Record<Key, string>> = { en, ro };
export type Lang = "en" | "ro";

type I18n = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  /** Format a UTC instant as a date and time in the cabinet timezone. */
  dateTime: (iso: string, tz: string) => string;
  date: (iso: string, tz: string) => string;
  time: (iso: string, tz: string) => string;
};

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem("lang");
    if (stored === "en" || stored === "ro") return stored;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith("ro") ? "ro" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("lang", l);
    } catch {
      /* ignore */
    }
    document.documentElement.lang = l;
  }, []);

  const value = useMemo<I18n>(() => {
    const locale = lang === "ro" ? "ro-RO" : "en-GB";
    const fmt = (iso: string, tz: string, opts: Intl.DateTimeFormatOptions) =>
      new Intl.DateTimeFormat(locale, { timeZone: tz, ...opts }).format(new Date(iso));
    return {
      lang,
      setLang,
      t: (key, vars) =>
        dictionaries[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`)),
      dateTime: (iso, tz) => fmt(iso, tz, { dateStyle: "medium", timeStyle: "short" }),
      date: (iso, tz) => fmt(iso, tz, { dateStyle: "medium" }),
      time: (iso, tz) => fmt(iso, tz, { hour: "2-digit", minute: "2-digit" }),
    };
  }, [lang, setLang]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}
